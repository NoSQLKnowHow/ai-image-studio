"""What the studio does with readings (DESIGN.md §38.6 to §38.8): checking a request for one, making its pieces, giving the worker the next part to speak,
taking in each finished piece, and telling the page how a reading stands.

The job manager owns the queue and the worker; this module owns the meaning of a reading. The two meet in a handful of calls: `build` (a request becomes a
queued reading), `job_for` (the next part, as a worker job), `accept_piece` (a piece the worker finished), `parts_left` (is there another part), and
`readings` (the `reading` object in a run's payload).
"""

from __future__ import annotations

import json
import math
import secrets
import shutil
import sqlite3
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path
from typing import Any, Optional, Sequence

from .. import wavfile
