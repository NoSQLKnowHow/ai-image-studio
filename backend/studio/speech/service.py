from ..storage import Storage
from . import SPOKEN_CHARS_PER_SECOND, registry
from .store import SpeechStore
from .text.model import Paragraph
from .text.pieces import make_pieces

MAX_PARTS = 1000
MAX_TITLE_CHARS = 200
MAX_STYLE_CHARS = 300
MAX_PIECES = 60_000  # about 1,500,000 characters at the smallest allowance an engine has; a ceiling on rows, not a limit anyone should meet
DISK_MARGIN = 1.2  # the audio is estimated, and the estimate is made 20% larger
DISK_RESERVE = 1024 ** 3  # and a gigabyte is kept free besides, for the database, the thumbnails and the next job
SAMPLE_BYTES = 2  # 16-bit mono


class ReadingRefused(Exception):
    """A request for a reading (or something done to one) was refused. `status` and `code` are the response's; `field` names what is wrong where one thing is."""

    def __init__(self, status: int, code: str, message: str, field: Optional[str] = None, hint: Optional[str] = None):
        super().__init__(message)
        self.status, self.code, self.message, self.field, self.hint = status, code, message, field, hint


@dataclass
class ParagraphSpec:
    kind: str
    text: str


@dataclass
class PartSpec:
    title: str
    paragraphs: list[ParagraphSpec]


@dataclass
class ReadingSpec:
    """A request for a reading, as the route read it."""

    title: str
    source: dict[str, Any]
    engine: str
    voice: str = ""  # a preset's id; empty when `saved_voice` is given
    saved_voice: Optional[str] = None  # the id of a voice the person made
    style: Optional[str] = None
    language: Optional[str] = None
    parts: list[PartSpec] = field(default_factory=list)


@dataclass
class BuiltReading:
    """A request that has been checked and turned into rows, ready to insert."""

    run: dict[str, Any]
    parts: list[dict[str, Any]]
    pieces: list[dict[str, Any]]
    seconds: float  # the length of audio it will make, estimated


def audio_info(options: dict[str, Any], part_title: str, created_at: str) -> dict[str, str]:
    """The note written into every WAV of a reading (DESIGN.md §38.4): that it is machine-generated speech, by what, and the engine's licence notice."""
    voice = options.get("voice") or {}
    kind = {"preset": "preset", "saved": voice.get("saved_kind") or "saved"}.get(voice.get("kind"), "preset")
    note = f"Generated by {options.get('engine_title') or options.get('engine')}, voice {voice.get('label') or voice.get('id')} ({kind}): machine-generated speech."
    if voice.get("kind") == "saved" and voice.get("saved_kind") == "cloned":
        note += " Made from a recording of a voice, used with the speaker's agreement."
    licence = options.get("licence") or {}
    if licence.get("notice"):
        note += " " + licence["notice"]
    return {"title": part_title[:200], "software": "ai-image-studio", "comment": note, "date": created_at[:10]}


class SpeechService:
    def __init__(self, settings: Settings, db: Database, storage: Storage):
        self.settings, self.db, self.storage = settings, db, storage
        self.store = SpeechStore(db)

    # ------------------------------------------------------------------ a request becomes a reading
    def build(self, spec: ReadingSpec, engines: dict[str, dict[str, Any]]) -> BuiltReading:
        """Check a request and make its rows. `engines` is what `capabilities.speech.engines` says, by id. Raises ReadingRefused, naming the field where
        one is at fault (criteria 274, 264). Nothing is written."""
        title = " ".join(spec.title.split())[:MAX_TITLE_CHARS] or "Reading"
        entry = engines.get(spec.engine)
        if entry is None:
            raise ReadingRefused(422, "unknown_engine", f"There is no speech engine {spec.engine!r} on this server.", "engine")
        if entry["state"] == "checking":  # not a verdict: the check made at start-up has not finished, and the page disables Start until it has
            raise ReadingRefused(409, "engine_checking", f"{entry.get('title') or spec.engine} is still being checked. Try again in a moment.", "engine")
        if entry["state"] not in ("ready", "needs_memory"):
            raise ReadingRefused(409, "engine_unavailable", entry.get("reason") or "That speech engine cannot run here.", "engine", entry.get("hint"))
        info = registry.info(spec.engine)
        presets = {v.id: v for v in registry.presets(spec.engine)}

        saved_row: Optional[sqlite3.Row] = None
        if spec.saved_voice:
            saved_row = self.store.voice(spec.saved_voice)
            if saved_row is None:
                raise ReadingRefused(422, "unknown_voice", "That voice is not among the voices you made (it may have been deleted).", "voice")
            if not info.can_clone or saved_row["engine"] != spec.engine:
                raise ReadingRefused(422, "voice_engine", f"That voice was made for another engine, so {info.title} cannot speak in it.", "voice")
            variant = registry.variant_for(info, "reading", True)
            voice = {"kind": "saved", "id": saved_row["id"], "label": saved_row["name"], "saved_kind": saved_row["kind"]}
            styleable = False  # a saved voice is spoken through the clone variant, which takes no style note (DESIGN.md §38.1)
        else:
            preset = presets.get(spec.voice)
            if preset is None:
                raise ReadingRefused(422, "unknown_voice", f"{info.title} has no voice called {spec.voice!r}.", "voice")
            variant = registry.variant_for(info, "reading", False)
            voice = {"kind": "preset", "id": preset.id, "label": preset.label, "gender": preset.gender, "accent": preset.accent}
            styleable = info.can_style and preset.styleable
        style = " ".join((spec.style or "").split()) or None
        if style is not None:
            if not styleable:
                raise ReadingRefused(422, "no_style", "This voice takes no style note; leave the box empty.", "style")
            if len(style) > MAX_STYLE_CHARS:
                raise ReadingRefused(422, "style_too_long", f"A style note is at most {MAX_STYLE_CHARS} characters.", "style")
        language: Optional[str] = None
        if spec.language:
            known = {name.lower(): name for name in info.languages}
            if not known:
                raise ReadingRefused(422, "no_language", f"{info.title} takes no language setting; the voice decides.", "language")
            if spec.language.strip().lower() not in known:
                raise ReadingRefused(422, "unknown_language", f"{info.title} does not speak {spec.language!r}. It speaks: {', '.join(info.languages)}.", "language")
            language = known[spec.language.strip().lower()]

        if not spec.parts or len(spec.parts) > MAX_PARTS:
            raise ReadingRefused(422, "parts", f"A reading has between 1 and {MAX_PARTS} parts.", "parts")
        run_id = secrets.token_hex(16)
        base_seed = secrets.randbelow(2 ** 31)
        parts: list[dict[str, Any]] = []
        pieces: list[dict[str, Any]] = []
        total_chars = 0
        for given in spec.parts:
            paragraphs = []
            for p in given.paragraphs:
                if p.kind not in ("heading", "paragraph"):
                    raise ReadingRefused(422, "paragraph_kind", f"A paragraph is a heading or a paragraph, not {p.kind!r}.", "parts")
                text = " ".join(p.text.split())
                if text:
                    if len(text) > self.settings.speech_max_chars:
                        raise ReadingRefused(413, "too_large", "One paragraph is longer than a whole reading may be.", "parts")
                    paragraphs.append(Paragraph(p.kind, text))
            made = make_pieces(paragraphs, info.max_chars, info.min_chars)
            if not made:
                continue  # a part with nothing to say is left out rather than refused: the page leaves out what the person unticked
            part_idx = len(parts)
            chars = sum(len(m.text) for m in made)
            total_chars += chars
            if total_chars > self.settings.speech_max_chars:
                raise ReadingRefused(413, "too_large", f"The text has more than the {self.settings.speech_max_chars:,} characters one reading can hold.", "parts")
            parts.append({"run_id": run_id, "idx": part_idx, "title": " ".join(given.title.split())[:MAX_TITLE_CHARS] or f"Part {part_idx + 1}", "chars": chars})
            for idx, m in enumerate(made):
                pieces.append({"run_id": run_id, "part_idx": part_idx, "idx": idx, "kind": m.kind, "text": m.text, "chars": len(m.text),
                               "continues": int(m.continues), "seed": (base_seed + len(pieces)) % (2 ** 31)})
        if not parts:
            raise ReadingRefused(422, "empty", "There is no text to read.", "parts", "Include at least one part that has some words in it.")
        if len(pieces) > MAX_PIECES:
            raise ReadingRefused(413, "too_large", "That text would need more pieces than a reading can hold; make two readings.", "parts")

        seconds = total_chars / SPOKEN_CHARS_PER_SECOND
        needed = int(seconds * info.sample_rate * SAMPLE_BYTES * DISK_MARGIN) + DISK_RESERVE
        free = shutil.disk_usage(self.settings.data_dir).free
        if free < needed:
            raise ReadingRefused(507, "storage_full", f"This reading needs about {needed / 1024 ** 3:.1f} GB of disk and {free / 1024 ** 3:.1f} GB is free.", None,
                                 "Delete readings you no longer need, or free disk space, and try again.")
        options = {
            "task": "reading", "engine": spec.engine, "engine_title": info.title, "variant": variant, "voice": voice, "style": style, "language": language,
            "source": spec.source, "title": title, "pause_ms": self.settings.speech_pause_ms, "licence": info.licence.as_dict(),
            "sample_rate": info.sample_rate, "chars": total_chars,
        }
        run = {
            "id": run_id, "created_at": utcnow(), "status": "queued", "mode": "speech", "prompt": title, "effective_prompt": title, "negative_prompt": None,
            "transparent": 0, "width": None, "height": None, "steps": 0, "cfg_scale": None, "seed": base_seed, "num_images": len(parts),
            "model_id": self.settings.speech_model_for(spec.engine) or info.model_id, "options_json": json.dumps(options), "lyrics": None,
        }
        return BuiltReading(run=run, parts=parts, pieces=pieces, seconds=seconds)

    # ------------------------------------------------------------------ the next part, as a job
    def job_for(self, row: sqlite3.Row) -> Optional[dict[str, Any]]:
        """The job that makes the next part of a reading, or None when every piece is made. Raises ValueError if the voice it uses has been deleted."""
        options = json.loads(row["options_json"])
        pieces = self.store.next_pieces(row["id"])
        if not pieces:
            return None
        voice = options["voice"]
        ref: Optional[dict[str, str]] = None
        preset = ""
        if voice["kind"] == "saved":
            saved = self.store.voice(voice["id"])
            if saved is None:
                raise ValueError(f"The voice {voice.get('label') or ''} that this reading uses has been deleted, so the rest cannot be made.".replace("  ", " "))
            ref = {"path": saved["ref_path"], "text": saved["ref_text"], "kind": saved["kind"]}
        else:
            preset = voice["id"]
        pause = int(options.get("pause_ms", 450))
        return {
            "run_id": row["id"], "mode": "speech", "task": "reading", "engine": options["engine"], "variant": options["variant"], "voice": preset, "ref": ref,
            "style": options.get("style"), "language": options.get("language"),
            "pieces": [{"key": f"{p['part_idx']}-{p['idx']}", "text": p["text"], "kind": p["kind"], "seed": p["seed"],
                        "out": f"speech/readings/{row['id']}/{p['part_idx']:04d}/{p['idx']:05d}.wav", "pause_ms": pause * 2 if p["kind"] == "heading" else pause}
                       for p in pieces],
        }

    # ------------------------------------------------------------------ taking in the worker's results
    def accept_piece(self, row: sqlite3.Row, event: dict[str, Any]) -> dict[str, int]:
        """Record a piece the worker reports as made: check the file, store what it says about itself, and fold the speed into the engine's average.
        Returns {part, idx, frames}. Raises StorageError or ValueError for a report that does not check out (the job manager fails the reading)."""
        run_id = row["id"]
        try:
            part_text, idx_text = str(event["key"]).split("-", 1)
            part_idx, idx = int(part_text), int(idx_text)
        except (KeyError, ValueError) as exc:
            raise ValueError(f"the worker reported a piece without a usable key: {event.get('key')!r}") from exc
        piece = self.store.piece(run_id, part_idx, idx)
        if piece is None:
            raise ValueError(f"the worker reported a piece this reading does not have: {event.get('key')!r}")
        path = self.storage.accept_worker_piece(str(event["path"]), run_id)
        info = wavfile.read_wav(path)
        if info.channels != 1:
            raise ValueError("a piece of speech must be mono")
        self.store.mark_piece_done(run_id, part_idx, idx, info.frames, info.sample_rate, info.bytes, self.storage.rel(path))
        options = json.loads(row["options_json"])
        work = float(event.get("work_seconds") or 0)
        spoken = int(event.get("spoken_chars") or 0)
        if work > 0 and spoken > 0:
            self.store.record_speed(options["engine"], options["variant"], spoken / work, utcnow())
        return {"part": part_idx, "idx": idx, "frames": info.frames}

    def mark_failed_piece(self, run_id: str, message: str) -> Optional[tuple[int, int]]:
        """The piece a failed job stopped at is the first one not made (the ones before it were taken in as they arrived): remember why on it, and return its
        (part, piece) so the message can say where. None if there is no such piece."""
        pending = self.store.next_pieces(run_id)
        if not pending:
            return None
        first = pending[0]
        self.store.set_piece_error(run_id, first["part_idx"], first["idx"], message[:500])
        return first["part_idx"], first["idx"]

    def pieces_left(self, run_id: str) -> int:
        return self.store.remaining(run_id)[1]

    # ------------------------------------------------------------------ describing a reading
    def readings(self, rows: Sequence[sqlite3.Row]) -> dict[str, dict[str, Any]]:
        """The `reading` object of each speech run among `rows` (DESIGN.md §38.9): where it stands, part by part, and how long it will take."""
        speech_rows = [r for r in rows if r["mode"] == "speech"]
        totals = self.store.totals([r["id"] for r in speech_rows])
        out: dict[str, dict[str, Any]] = {}
        for row in speech_rows:
            options = json.loads(row["options_json"])
            t = totals[row["id"]]
            rate = t["sample_rate"] or options.get("sample_rate") or 24000
            parts = []
            for part in t["parts"]:
                state = "done" if part["pieces"] and part["made"] == part["pieces"] else "started" if part["made"] else "waiting"
                parts.append({"idx": part["idx"], "title": part["title"], "chars": part["chars"], "pieces": part["pieces"], "made": part["made"],
                              "seconds": round(part["frames"] / (part["sample_rate"] or rate), 2), "state": state})
            remaining_chars, _remaining_pieces = self.store.remaining(row["id"])
            speed = self.store.speed(options["engine"], options["variant"])
            made_seconds = t["frames"] / rate
            position = self.store.position(row["id"])
            out[row["id"]] = {
                "engine": options["engine"], "engine_title": options.get("engine_title"), "variant": options["variant"], "voice": options["voice"],
                "style": options.get("style"), "language": options.get("language"), "source": options.get("source"), "licence": options.get("licence"),
                "title": options.get("title"), "parts": parts, "parts_total": len(parts), "parts_done": sum(1 for p in parts if p["state"] == "done"),
                "pieces_total": t["pieces"], "pieces_done": t["made"], "seconds_made": round(made_seconds, 2), "bytes": t["bytes"], "sample_rate": rate,
                # between two parts a reading is queued, with something made: the card says it is waiting for its turn and not that it has not started
                "waiting": row["status"] == "queued" and t["made"] > 0,
                "seconds_total": round(made_seconds + remaining_chars / SPOKEN_CHARS_PER_SECOND, 1),
                "seconds_to_go": math.ceil(remaining_chars / speed) if speed and remaining_chars and row["status"] in ("queued", "running") else None,
                "position": {"part": position["part_idx"], "piece": position["piece_idx"], "offset_ms": position["offset_ms"]} if position else None,
            }
        return out

    def part_detail(self, row: sqlite3.Row, part_idx: int) -> Optional[dict[str, Any]]:
        """One part with its pieces, for the reading view (DESIGN.md §38.7): the text of each, where it starts, and where to fetch its audio."""
        part = next((p for p in self.store.parts(row["id"]) if p["idx"] == part_idx), None)
        if part is None:
            return None
        pieces = self.store.pieces(row["id"], part_idx)
        out, start = [], 0
        for p in pieces:
            done = p["status"] == "done"
            # pieces are made in order, so the ones that are made are a run from the start of the part, and each starts where the one before it ended
            out.append({"idx": p["idx"], "kind": p["kind"], "text": p["text"], "continues": bool(p["continues"]), "status": p["status"], "frames": p["frames"],
                        "start_frame": start if done else None, "error": p["error"],
                        "url": f"/api/speech/{row['id']}/parts/{part_idx}/pieces/{p['idx']}.wav" if done else None})
            if done:
                start += p["frames"] or 0
        complete = bool(pieces) and all(p["status"] == "done" for p in pieces)
        rate = next((p["sample_rate"] for p in pieces if p["sample_rate"]), None)
        return {"idx": part["idx"], "title": part["title"], "chars": part["chars"], "complete": complete, "sample_rate": rate, "total_frames": start,
                "url": f"/api/speech/{row['id']}/parts/{part_idx}.wav" if complete else None,
                "download_url": f"/api/speech/{row['id']}/parts/{part_idx}.wav?download=1" if complete else None, "pieces": out}

    def part_files(self, row: sqlite3.Row, part_idx: int) -> list[Path]:
        """The files of a complete part's pieces, in order. Empty if the part is not complete (or not there)."""
        pieces = self.store.pieces(row["id"], part_idx)
        if not pieces or any(p["status"] != "done" for p in pieces):
            return []
        return [self.storage.abs(p["path"]) for p in pieces]

    def created(self, row: sqlite3.Row) -> datetime:
        from ..serialize import parse_ts

        return parse_ts(row["created_at"])
